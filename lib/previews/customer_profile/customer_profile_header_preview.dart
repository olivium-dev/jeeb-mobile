/// An Arabic name beside a Latin email — the majority case for this app, and
/// the mixed-direction state `AutoDirectionText` exists to serve.
///
/// The two lines resolve their direction independently, from their own first
/// strong character, so in the **EN light** rendering the Arabic name lays out
/// RTL inside a left-aligned column while the email stays LTR (and the mirror
/// image of that in **AR RTL**). Whichever locale you are in, one of these two
/// lines runs against the ambient direction, and `CrossAxisAlignment.start`
/// aligns the *boxes*, not the glyphs — so this is the state where a
/// half-mirrored column would show up.
@JeebPreview(name: 'Arabic name, Latin email', size: _wrappingBox)
Widget customerProfileHeaderArabicName() => _hosted(
      name: 'كمال حاج الطرابلسي',
      email: 'kamalhaaj@gmail.com',
      isVerified: true,
      rating: 4.9,
      ratingCount: 312,
    );

/// The layout ceiling: longest plausible full name and a long email.
///
/// `_NameText` wraps its `AutoDirectionText` in a `Flexible` but passes no
/// `maxLines`/`overflow`, so unlike `ClientHomeGreeting` — which clamps its
/// name to `maxLines: 1, TextOverflow.ellipsis` — a long name here does not
/// ellipsize. It wraps and grows the header: measured, this name takes 3 lines
/// of the 222 dp column and makes the header 236 dp tall at 1x and **592 dp at
/// 200%**, which is why this box is a whole phone viewport. On the real screen
/// the header is the first child of the profile `ListView`, so those 592 dp
/// push every account row below the fold.
///
/// The verified badge is the other thing to look at. `_NameRow` centres it
/// (`CrossAxisAlignment.center`) against the *whole* wrapped block, so on a
/// 3-line name it floats beside the middle line — measured at y 94–114 against
/// a name block spanning y 56–152 — reading as an orphaned glyph rather than as
/// a mark on the name.
@JeebPreview(name: 'Long name + long email', size: _phoneScreenBox)
