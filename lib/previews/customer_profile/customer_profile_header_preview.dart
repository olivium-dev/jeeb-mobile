/// Widget previews for [CustomerProfileHeader] — run with
/// `flutter widget-preview start`.
///
/// The header is a pure [StatelessWidget] over six plain fields, so every state
/// below is just a constructor call: no cubit, no repository, nothing to seed.
/// It is network-free by construction, not merely by [jeebPreviewHost]'s guard.
///
/// **Why there is no "avatar photo" state.** `avatarUrl` is the one field that
/// would reach the network (`OmdsProfileAvatar` → `OmdsCachedImage`), and a CDN
/// URL resolves in neither the canvas nor a test — both fall back to the same
/// initials placeholder the `null` states already show. A preview that renders
/// identically to its neighbours is the exact failure `expectedText` exists to
/// catch, so every state here passes `avatarUrl: null` and the photo path is
/// left to the screen goldens.
///
/// Fixture values are the ones already asserted in
/// `test/customer_profile_screen_test.dart` (`_ratedCustomer`,
/// `_unratedCustomer`, `_jeeberCustomer`) so the previews and the screen test
/// describe the same customers.
///
/// **Measured geometry** (390 dp wide, bundled Inter, from the render tree —
/// not eyeballed). The identity column gets 222 dp: 390 − 24 − 24 of
/// directional padding − 80 dp avatar − 12 dp gap − 28 dp for the verified
/// badge and its gap. Header heights:
///
/// | state              | 1x     | 200% text |
/// |--------------------|--------|-----------|
/// | cold start         | 152 dp | 172 dp    |
/// | rated / unrated    | 152 dp | 320 dp    |
/// | Arabic name        | 184 dp | 384 dp    |
/// | synthetic identity | 204 dp | 424 dp    |
/// | long name          | 236 dp | 592 dp    |
///
/// Each canvas box below is sized to hold its own 200% rendering, so an
/// overflow stripe in the canvas means a real regression — except in the last
/// state, where the overflow IS the subject.
library;

import 'package:flutter/material.dart';

import '../harness/jeeb_preview.dart';
import '../../features/customer_profile/presentation/widgets/customer_profile_header.dart';

/// Phone width; holds the 56 dp top inset + the 80 dp avatar + a
/// single-line-per-row identity column, with room for the 320 dp the same
/// content needs at 200% text.
const Size _headerBox = Size(390, 340);

/// For the states whose identity column wraps to a second line even at 1x
/// (long email, Arabic name) — 424 dp at 200% is the tallest of them.
const Size _wrappingBox = Size(390, 440);

/// A whole phone viewport, because that is the point of the state it frames:
/// at 200% text the header alone fills the screen.
const Size _phoneScreenBox = Size(390, 600);

/// One specimen. Mirrors the argument list `CustomerProfileScreen` passes at
/// `lib/features/customer_profile/presentation/customer_profile_screen.dart:142`
/// — same six fields, same order, so a preview cannot drift from the call site.
Widget _hosted({
  String? name,
  String? email,
  bool isVerified = false,
  double? rating,
  int ratingCount = 0,
}) {
  return CustomerProfileHeader(
    name: name,
    email: email,
    // Always null — see the library doc above.
    avatarUrl: null,
    isVerified: isVerified,
    rating: rating,
    ratingCount: ratingCount,
  );
}

/// The happy path: a rated, verified customer with an email on file
/// (`_ratedCustomer` from the screen test).
///
/// All four elements present at once — initials avatar, name + SealCheck badge,
/// "★ 4.8 · 42 Reviews", email — the only state where the identity column runs
/// to its full three rows. Two things to check in **AR RTL dark**: the star
/// leads the rating text (a plain [Row], so it relies entirely on ambient
/// [Directionality]), and the Latin email still reads LTR inside the mirrored
/// column — that is what `AutoDirectionText` is there for.
///
/// The dark rendering is also where the name's colour shows itself: it is
/// painted with `colorScheme.secondaryContainer`, a *container* role used as
/// ink. On white that is brand navy (17:1), but the dark scheme is generated by
/// `ColorScheme.fromSeed`, where the same role is #44455A — 1.98:1 against the
/// #131318 surface, under the 3:1 WCAG floor for large text. The rating and
/// email lines beside it use `onSurfaceVariant` and stay at 10.9:1.
@JeebPreview(name: 'Rated + verified', size: _headerBox)
Widget customerProfileHeaderRated() => _hosted(
      name: 'Sami Fawaz',
      email: 'kamalhaaj@gmail.com',
      isVerified: true,
      rating: 4.8,
      ratingCount: 42,
    );

/// The seeded customer: verified, but never rated and with no email
